-- Schema PostgreSQL cuối cùng cho khởi tạo mới (23 bảng).
-- Mọi thay đổi cấu trúc được cập nhật trực tiếp trong file này.
-- IF NOT EXISTS chỉ cho phép khởi động lại cùng schema; không nâng cấp database cũ.

-- Mã nghiệp vụ được sinh từ ID: ổn định, duy nhất và không cắt số khi vượt 999.
-- Các ID số vẫn là khóa nội bộ; không dùng mã này cho OTP/token hay phân quyền.
CREATE OR REPLACE FUNCTION business_code(prefix text, identifier integer, min_width integer DEFAULT 3)
RETURNS text LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT prefix || '_' || lpad(identifier::text, greatest(min_width, length(identifier::text)), '0');
$$;

-- 1. ROLE (Vai trò)
CREATE TABLE IF NOT EXISTS role (
    role_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code text GENERATED ALWAYS AS (business_code('VT', role_id)) STORED UNIQUE,
    role_name            text NOT NULL UNIQUE,
    description          text,
    requires_approval    INTEGER NOT NULL DEFAULT 1 CHECK (requires_approval IN (0,1)),
    CONSTRAINT role_name_allowed CHECK (role_name IN ('USER','DOCTOR','RECEPTIONIST','NURSE','ADMIN'))
);

-- 2. USERS (Tài khoản người dùng)
CREATE TABLE IF NOT EXISTS users (
    user_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_code text GENERATED ALWAYS AS (business_code('TK', user_id)) STORED UNIQUE,
    role_id            INTEGER NOT NULL REFERENCES role(role_id),
    full_name          text NOT NULL CHECK (trim(full_name) <> ''),
    phone              text UNIQUE,
    email              text UNIQUE,
    dob                DATE CHECK (dob BETWEEN DATE '1900-01-01' AND (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Saigon')::date),
    gender             text CHECK (gender IN ('Nam','Nữ','Khác')),
    id_card            text UNIQUE CHECK (id_card ~ '^[0-9]{12}$'),
    address            text,
    emergency_contact_name text,
    emergency_contact_phone text CHECK (emergency_contact_phone ~ '^\+?[0-9]{9,15}$'),
    emergency_contact_relationship text,
    avatar_url         text,
    password_hash      text NOT NULL CONSTRAINT users_password_hash_nonempty CHECK (trim(password_hash) <> ''),
    approval_status    text NOT NULL DEFAULT 'PENDING'
        CHECK (approval_status IN ('PENDING','APPROVED','REJECTED')),
    account_status     text NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE','LOCKED')),
    email_verified     INTEGER NOT NULL DEFAULT 0 CHECK (email_verified IN (0,1)),
    deleted_at         TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_phone_nonempty CHECK (phone IS NULL OR trim(phone) <> ''),
    CONSTRAINT users_email_nonempty CHECK (email IS NULL OR trim(email) <> '')
);

-- 3. AUTH_TOKEN (Token xác thực)
CREATE TABLE IF NOT EXISTS auth_token (
    token_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER NOT NULL REFERENCES users(user_id),
    token_type    text NOT NULL CHECK (token_type IN ('RESET_PASSWORD','VERIFY_EMAIL','OTP')),
    token_hash    text NOT NULL CHECK (trim(token_hash) <> ''),
    expires_at    TIMESTAMPTZ NOT NULL,
    used_at       TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT auth_token_expiry CHECK (expires_at > created_at),
    CONSTRAINT auth_token_used_time CHECK (used_at IS NULL OR used_at >= created_at)
);

-- 4. PATIENT (Hồ sơ bệnh nhân)
CREATE TABLE IF NOT EXISTS patient (
    patient_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_code text GENERATED ALWAYS AS (business_code('BN', patient_id)) STORED UNIQUE,
    user_id             INTEGER REFERENCES users(user_id),
    full_name           text NOT NULL CHECK (trim(full_name) <> ''),
    dob                 DATE CHECK (dob BETWEEN DATE '1900-01-01' AND (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Saigon')::date),
    gender              text CHECK (gender IN ('Nam','Nữ','Khác')),
    id_card             text UNIQUE CHECK (id_card ~ '^([0-9]{9}|[0-9]{12})$'),
    address             text,
    phone               text,
    email               text,
    emergency_contact_name text,
    emergency_contact_phone text CHECK (emergency_contact_phone ~ '^\+?[0-9]{9,15}$'),
    emergency_contact_relationship text,
    health_insurance    text,
    archived_at         TIMESTAMPTZ,
    relationship        text CHECK (relationship IN ('SELF','PARENT','CHILD','SPOUSE','OTHER')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Người đặt hộ được chọn lại hồ sơ đã thêm và đặt lượt mới, không tự có quyền
-- xem toàn bộ lịch sử của tài khoản bệnh nhân. Lượt họ tạo lưu created_by_id.
CREATE TABLE IF NOT EXISTS patient_delegate (
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    user_id INTEGER NOT NULL REFERENCES users(user_id),
    relationship TEXT NOT NULL CHECK (relationship IN ('PARENT','CHILD','SPOUSE','OTHER')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (patient_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_patient_delegate_user ON patient_delegate(user_id);

-- 5. DEPARTMENT (Chuyên khoa)
CREATE TABLE IF NOT EXISTS department (
    department_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code text GENERATED ALWAYS AS (business_code('CK', department_id)) STORED UNIQUE,
    name             text NOT NULL CHECK (trim(name) <> ''),
    description      text,
    is_active        INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 6. DOCTOR_PROFILE (Hồ sơ bác sĩ)
CREATE TABLE IF NOT EXISTS doctor_profile (
    doctor_profile_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_code text GENERATED ALWAYS AS (business_code('BS', doctor_profile_id)) STORED UNIQUE,
    user_id              INTEGER NOT NULL UNIQUE REFERENCES users(user_id),
    department_id        INTEGER NOT NULL REFERENCES department(department_id),
    academic_degree      text,
    specialization       text,
    experience_years     integer NOT NULL DEFAULT 0 CHECK (experience_years >= 0),
    introduction         text,
    consultation_fee     BIGINT NOT NULL DEFAULT 0 CHECK (consultation_fee >= 0),
    is_active            INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. ROOM (Phòng khám)
CREATE TABLE IF NOT EXISTS room (
    room_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code text GENERATED ALWAYS AS (business_code('PH', room_id)) STORED UNIQUE,
    department_id    INTEGER NOT NULL REFERENCES department(department_id),
    room_name        text NOT NULL CHECK (trim(room_name) <> ''),
    description      text,
    is_active        INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 8. WORK_SCHEDULE (Lịch làm việc)
CREATE TABLE IF NOT EXISTS work_schedule (
    schedule_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_code text GENERATED ALWAYS AS (business_code('CA', schedule_id)) STORED UNIQUE,
    doctor_profile_id     INTEGER NOT NULL REFERENCES doctor_profile(doctor_profile_id),
    room_id               INTEGER NOT NULL REFERENCES room(room_id),
    work_date             DATE NOT NULL,
    start_time            TIME NOT NULL,
    end_time              TIME NOT NULL,
    max_quota             integer NOT NULL CHECK (max_quota > 0),
    booked_count          integer NOT NULL DEFAULT 0,
    slot_minutes          INTEGER NOT NULL DEFAULT 30 CHECK (slot_minutes IN (15,30)),
    schedule_status       text NOT NULL DEFAULT 'OPEN'
        CHECK (schedule_status IN ('OPEN','FULL','CLOSED','UNAVAILABLE')),
    unavailable_reason    text,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT schedule_time_order CHECK (end_time > start_time),
    CONSTRAINT schedule_quota CHECK (booked_count BETWEEN 0 AND max_quota),
    CONSTRAINT schedule_doctor_start_unique UNIQUE (doctor_profile_id, work_date, start_time),
    CONSTRAINT schedule_room_start_unique UNIQUE (room_id, work_date, start_time)
);

-- 9. ENCOUNTER (Lượt khám)
CREATE TABLE IF NOT EXISTS encounter (
    encounter_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_code text GENERATED ALWAYS AS (business_code('LK', encounter_id)) STORED UNIQUE,
    encounter_type           text NOT NULL CHECK (encounter_type IN ('ONLINE','WALK_IN')),
    patient_id           INTEGER NOT NULL REFERENCES patient(patient_id),
    doctor_profile_id    INTEGER NOT NULL REFERENCES doctor_profile(doctor_profile_id),
    schedule_id          INTEGER NOT NULL REFERENCES work_schedule(schedule_id),
    room_id              INTEGER REFERENCES room(room_id),
    created_by_id        INTEGER REFERENCES users(user_id),
    consultation_fee_snapshot BIGINT CHECK (consultation_fee_snapshot >= 0),
    deposit_amount_snapshot   BIGINT CHECK (deposit_amount_snapshot >= 0),
    symptoms             text,
    registration_details jsonb CHECK (registration_details IS NULL OR jsonb_typeof(registration_details) = 'object'),
    encounter_status         text NOT NULL DEFAULT 'CONFIRMED'
        CHECK (encounter_status IN ('HOLDING','CONFIRMED','CHECKED_IN','IN_PROGRESS','COMPLETED','CANCELLED','NO_SHOW','EXPIRED')),
    ticket_code          TEXT UNIQUE,
    appointment_end_at   TIMESTAMPTZ NOT NULL,
    estimated_exam_at    TIMESTAMPTZ NOT NULL,
    qr_code              text,
    hold_expires_at      TIMESTAMPTZ,
    checked_in_at        TIMESTAMPTZ,
    cancelled_by_id      INTEGER REFERENCES users(user_id),
    cancel_reason        text,
    cancel_origin        text CHECK (cancel_origin IN ('PATIENT','HOSPITAL')),
    cancelled_at         TIMESTAMPTZ,
    refund_reference_at  TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT encounter_snapshot_pair CHECK ((consultation_fee_snapshot IS NULL) = (deposit_amount_snapshot IS NULL)),
    CONSTRAINT encounter_deposit_limit CHECK (deposit_amount_snapshot <= consultation_fee_snapshot),
    CONSTRAINT encounter_slot_order CHECK (appointment_end_at > estimated_exam_at),
    CONSTRAINT encounter_hold_online_only CHECK (hold_expires_at IS NULL OR encounter_type = 'ONLINE'),
    CONSTRAINT encounter_holding_expiry CHECK (
        encounter_status <> 'HOLDING' OR (encounter_type = 'ONLINE' AND hold_expires_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS encounter_active_slot_unique
ON encounter(schedule_id, estimated_exam_at)
WHERE encounter_status IN ('HOLDING','CONFIRMED','CHECKED_IN','IN_PROGRESS','COMPLETED');

-- 10. ENCOUNTER_STATUS_LOG (Lịch sử trạng thái lượt khám)
CREATE TABLE IF NOT EXISTS encounter_status_log (
    log_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_code text GENERATED ALWAYS AS (business_code('NKTT', log_id)) STORED UNIQUE,
    encounter_id         INTEGER NOT NULL REFERENCES encounter(encounter_id),
    old_status       text CHECK (old_status IN ('HOLDING','CONFIRMED','CHECKED_IN','IN_PROGRESS','COMPLETED','CANCELLED','NO_SHOW','EXPIRED')),
    new_status       text NOT NULL CHECK (new_status IN ('HOLDING','CONFIRMED','CHECKED_IN','IN_PROGRESS','COMPLETED','CANCELLED','NO_SHOW','EXPIRED')),
    changed_by_id    INTEGER NOT NULL REFERENCES users(user_id),
    note             text,
    changed_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 11. ENCOUNTER_TRANSFER_LOG (Lịch sử chuyển bác sĩ)
CREATE TABLE IF NOT EXISTS encounter_transfer_log (
    log_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_code text GENERATED ALWAYS AS (business_code('NKCD', log_id)) STORED UNIQUE,
    encounter_id             INTEGER NOT NULL REFERENCES encounter(encounter_id),
    old_doctor_id        INTEGER NOT NULL REFERENCES doctor_profile(doctor_profile_id),
    new_doctor_id        INTEGER NOT NULL REFERENCES doctor_profile(doctor_profile_id),
    transferred_by_id    INTEGER NOT NULL REFERENCES users(user_id),
    reason               text,
    transferred_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT transfer_different_doctor CHECK (old_doctor_id <> new_doctor_id)
);

-- 12. PAYMENT (Thanh toán)
CREATE TABLE IF NOT EXISTS payment (
    payment_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_code text GENERATED ALWAYS AS (business_code('TT', payment_id)) STORED UNIQUE,
    encounter_id              INTEGER NOT NULL REFERENCES encounter(encounter_id),
    payment_type          text NOT NULL CHECK (payment_type IN ('DEPOSIT','EXAM_FEE','REFUND')),
    amount                BIGINT NOT NULL CHECK (amount >= 0),
    payment_method        text NOT NULL CHECK (payment_method IN ('CASH','BANK','EWALLET','CARD')),
    transaction_status    text NOT NULL DEFAULT 'PENDING'
        CHECK (transaction_status IN ('PENDING','SUCCESS','FAILED','REFUNDED')),
    transaction_code      text UNIQUE,
    original_payment_id   INTEGER REFERENCES payment(payment_id),
    created_by_id         INTEGER REFERENCES users(user_id),
    processed_by_id       INTEGER REFERENCES users(user_id),
    reason                text,
    failure_reason        text,
    result_received_at    TIMESTAMPTZ,
    paid_at               TIMESTAMPTZ,
    refunded_at           TIMESTAMPTZ,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 13. MEDICAL_RECORD (Hồ sơ khám bệnh)
CREATE TABLE IF NOT EXISTS medical_record (
    record_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_code text GENERATED ALWAYS AS (business_code('BA', record_id)) STORED UNIQUE,
    encounter_id        INTEGER NOT NULL UNIQUE REFERENCES encounter(encounter_id),
    diagnosis       text,
    treatment       text,
    doctor_notes    text,
    examined_at     TIMESTAMPTZ,
    version         INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    revision_history JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(revision_history)='array'),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 14. PRESCRIPTION_ITEM (Chi tiết đơn thuốc)
CREATE TABLE IF NOT EXISTS prescription_item (
    item_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code text GENERATED ALWAYS AS (business_code('DT', item_id)) STORED UNIQUE,
    record_id          INTEGER NOT NULL REFERENCES medical_record(record_id),
    medication_name    text NOT NULL CHECK (trim(medication_name) <> ''),
    dosage             text,
    quantity           integer NOT NULL CHECK (quantity > 0),
    instructions       text
);

-- 15. REVIEW (Đánh giá)
CREATE TABLE IF NOT EXISTS review (
    review_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_code text GENERATED ALWAYS AS (business_code('DG', review_id)) STORED UNIQUE,
    record_id     INTEGER NOT NULL REFERENCES medical_record(record_id),
    rating        integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment       text,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_review_record ON review(record_id);

-- 16. NOTIFICATION (Thông báo)
CREATE TABLE IF NOT EXISTS notification (
    notification_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_code text GENERATED ALWAYS AS (business_code('TB', notification_id)) STORED UNIQUE,
    user_id              INTEGER NOT NULL REFERENCES users(user_id),
    event_key            text,
    notification_type    text NOT NULL CHECK (trim(notification_type) <> ''),
    title                text NOT NULL CHECK (trim(title) <> ''),
    content              text NOT NULL,
    reference_type       text,
    reference_id         INTEGER,
    is_read              INTEGER NOT NULL DEFAULT 0 CHECK (is_read IN (0,1)),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notification_reference_pair CHECK (
        (reference_type IS NULL AND reference_id IS NULL) OR
        (reference_type IS NOT NULL AND trim(reference_type) <> '' AND reference_id IS NOT NULL)
    )
);

-- 17. ARTICLE (Bài viết)
CREATE TABLE IF NOT EXISTS article (
    article_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_code text GENERATED ALWAYS AS (business_code('BV', article_id)) STORED UNIQUE,
    author_id        INTEGER NOT NULL REFERENCES users(user_id),
    title            text NOT NULL CHECK (trim(title) <> ''),
    slug             text NOT NULL UNIQUE CHECK (trim(slug) <> ''),
    category         text,
    thumbnail_url    text,
    content          text NOT NULL,
    is_active        INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
    published_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 18. SYSTEM_CONFIGURATION (Cấu hình hệ thống)
CREATE TABLE IF NOT EXISTS system_configuration (
    config_key      text NOT NULL PRIMARY KEY CHECK (trim(config_key) <> ''),
    config_value    text NOT NULL,
    description     text,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 19. ROLE_REQUEST (Yêu cầu đổi vai trò)
CREATE TABLE IF NOT EXISTS role_request (
    request_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_code text GENERATED ALWAYS AS (business_code('YCVT', request_id)) STORED UNIQUE,
    user_id              INTEGER NOT NULL REFERENCES users(user_id),
    requested_role_id    INTEGER NOT NULL REFERENCES role(role_id),
    reason               text CHECK (reason IS NULL OR trim(reason) <> ''),
    request_status       text NOT NULL DEFAULT 'PENDING'
        CHECK (request_status IN ('PENDING','APPROVED','REJECTED')),
    reviewed_by_id       INTEGER REFERENCES users(user_id),
    reviewed_at          TIMESTAMPTZ,
    review_note          text CHECK (review_note IS NULL OR trim(review_note) <> ''),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT role_request_review CHECK (
        (request_status = 'PENDING' AND reviewed_by_id IS NULL AND reviewed_at IS NULL) OR
        (request_status IN ('APPROVED','REJECTED') AND reviewed_by_id IS NOT NULL AND reviewed_at IS NOT NULL)
    ),
    CONSTRAINT role_request_no_self_review CHECK (reviewed_by_id <> user_id),
    CONSTRAINT role_request_review_time CHECK (reviewed_at IS NULL OR reviewed_at >= created_at),
    CONSTRAINT role_request_rejection_note CHECK (request_status <> 'REJECTED' OR review_note IS NOT NULL)
);

-- 20. NURSE_ASSIGNMENT (Phân công điều dưỡng theo ca)
-- Phòng và chuyên khoa được xác định qua work_schedule, không lưu trùng ở đây.
CREATE TABLE IF NOT EXISTS nurse_assignment (
    assignment_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_code text GENERATED ALWAYS AS (business_code('PC', assignment_id)) STORED UNIQUE,
    nurse_id         INTEGER NOT NULL REFERENCES users(user_id),
    schedule_id      INTEGER NOT NULL REFERENCES work_schedule(schedule_id),
    assigned_by_id   INTEGER NOT NULL REFERENCES users(user_id),
    assigned_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at       TIMESTAMPTZ,
    revoked_by_id    INTEGER REFERENCES users(user_id),
    note             text,
    CONSTRAINT nurse_assignment_revocation CHECK ((revoked_at IS NULL) = (revoked_by_id IS NULL)),
    CONSTRAINT nurse_assignment_revocation_time CHECK (revoked_at IS NULL OR revoked_at >= assigned_at)
);

