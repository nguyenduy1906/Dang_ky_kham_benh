CREATE OR REPLACE FUNCTION check_department_leader_membership() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.ended_at IS NULL THEN
   PERFORM 1 FROM doctor_profile WHERE doctor_profile_id=NEW.doctor_profile_id AND department_id=NEW.department_id FOR UPDATE;
   IF NOT FOUND THEN RAISE EXCEPTION 'Leader must belong to the department' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS department_leader_membership ON department_leadership;
CREATE TRIGGER department_leader_membership BEFORE INSERT OR UPDATE ON department_leadership FOR EACH ROW EXECUTE FUNCTION check_department_leader_membership();

CREATE OR REPLACE FUNCTION protect_department_leader_transfer() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.department_id<>OLD.department_id AND EXISTS(SELECT 1 FROM department_leadership WHERE doctor_profile_id=OLD.doctor_profile_id AND ended_at IS NULL) THEN
   RAISE EXCEPTION 'End department leadership before transferring the doctor' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS protect_department_leader_transfer ON doctor_profile;
CREATE TRIGGER protect_department_leader_transfer BEFORE UPDATE OF department_id ON doctor_profile FOR EACH ROW EXECUTE FUNCTION protect_department_leader_transfer();

-- Lịch đi làm mặc định được sinh theo tuần T2–T6; ca khám/phòng vẫn ở work_schedule.
-- Chỉ lưu ngoại lệ nghỉ, không tạo vô hạn bản ghi cho từng tuần.
CREATE TABLE IF NOT EXISTS staff_leave_request (
    request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_code text GENERATED ALWAYS AS (business_code('NP', request_id)) STORED UNIQUE,
    user_id integer NOT NULL REFERENCES users(user_id),
    from_date date NOT NULL,
    to_date date NOT NULL,
    period text NOT NULL DEFAULT 'FULL_DAY' CHECK(period IN ('FULL_DAY','MORNING','AFTERNOON')),
    reason text NOT NULL CHECK(length(trim(reason)) BETWEEN 1 AND 1000),
    status text NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','APPROVED','REJECTED','CANCELLED')),
    reviewed_by_id integer REFERENCES users(user_id),
    reviewed_at timestamptz,
    review_note text,
    cancelled_at timestamptz,
    effects jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(effects)='object'),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK(to_date>=from_date AND to_date-from_date<=30),
    CHECK(reviewed_by_id IS NULL OR reviewed_by_id<>user_id),
    CHECK((status IN ('PENDING','CANCELLED') AND reviewed_by_id IS NULL AND reviewed_at IS NULL AND review_note IS NULL)
       OR (status IN ('APPROVED','REJECTED') AND reviewed_by_id IS NOT NULL AND reviewed_at IS NOT NULL
           AND review_note IS NOT NULL AND length(trim(review_note)) BETWEEN 1 AND 1000)),
    CHECK((status='CANCELLED')=(cancelled_at IS NOT NULL)),
    CHECK(reviewed_at IS NULL OR reviewed_at>=created_at),
    CHECK(cancelled_at IS NULL OR cancelled_at>=created_at)
);
CREATE INDEX IF NOT EXISTS staff_leave_user_dates ON staff_leave_request(user_id,from_date,to_date)
WHERE status IN ('PENDING','APPROVED');
CREATE INDEX IF NOT EXISTS staff_leave_status_created ON staff_leave_request(status,created_at DESC);
CREATE OR REPLACE TRIGGER trg_staff_leave_updated_at BEFORE UPDATE ON staff_leave_request
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Mã phiếu chỉ được cấp sau xác nhận/tiếp nhận; không cấp cho lượt đang giữ chỗ.
CREATE OR REPLACE FUNCTION assign_encounter_ticket() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.ticket_code IS NULL AND NEW.encounter_status IN ('CONFIRMED','CHECKED_IN','IN_PROGRESS','COMPLETED','NO_SHOW') THEN
        NEW.ticket_code := 'PK_' || to_char(NEW.estimated_exam_at AT TIME ZONE 'Asia/Saigon','YYYYMMDD')
                           || '_' || lpad(NEW.encounter_id::text,greatest(6,length(NEW.encounter_id::text)),'0');
    END IF;
    RETURN NEW;
END;
$$;
CREATE OR REPLACE TRIGGER trg_encounter_ticket BEFORE INSERT OR UPDATE ON encounter
FOR EACH ROW EXECUTE FUNCTION assign_encounter_ticket();

-- Đây là giao dịch giả lập của đồ án, không phải mã giao dịch ngân hàng thật.
CREATE OR REPLACE FUNCTION assign_payment_transaction() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.transaction_code IS NULL THEN
        NEW.transaction_code := CASE WHEN NEW.payment_type='REFUND' THEN 'HT_DEMO_' ELSE 'GD_DEMO_' END
            || to_char(NEW.created_at AT TIME ZONE 'Asia/Saigon','YYYYMMDD') || '_'
            || lpad(NEW.payment_id::text,greatest(6,length(NEW.payment_id::text)),'0');
    END IF;
    RETURN NEW;
END;
$$;
CREATE OR REPLACE TRIGGER trg_payment_transaction BEFORE INSERT ON payment
FOR EACH ROW EXECUTE FUNCTION assign_payment_transaction();

